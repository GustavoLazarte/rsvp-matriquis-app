export class I18nService {
  readonly lang = signal<Lang>('es');

  get current(): Lang {
    return this.lang();
  }

  setLang(l: Lang) {
    this.lang.set(l);
  }

  t(key: string): string {
    return T[this.current][key] ?? key;
  }

  tArr(key: string): any[] {
    return T[this.current][key] ?? [];
  }

  tObj(key: string): any[] {
    return T[this.current][key] ?? [];
  }
}
